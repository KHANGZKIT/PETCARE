-- Android: Java | Backend: Spring Boot + Spring Data JPA
-- Run this script once against an EMPTY database named pet_care.
-- It creates the schema only; no demo data is inserted.
-- ============================================================

BEGIN;

-- 1. Veterinary clinics
CREATE TABLE public.clinics (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(150) NOT NULL,
    address             VARCHAR(255) NOT NULL,
    area                VARCHAR(100) NOT NULL,
    phone               VARCHAR(20) NOT NULL UNIQUE,
    working_hours_note  VARCHAR(150),
    is_active           BOOLEAN NOT NULL DEFAULT TRUE
);

-- 2. Customers and clinic staff share one table
CREATE TABLE public.users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(100) NOT NULL,
    email           VARCHAR(150) NOT NULL UNIQUE,
    phone           VARCHAR(20) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    role            VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
    clinic_id       BIGINT,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_users_clinic
        FOREIGN KEY (clinic_id) REFERENCES public.clinics(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT chk_users_role
        CHECK (role IN ('CUSTOMER', 'STAFF')),
    CONSTRAINT chk_users_role_clinic
        CHECK (
            (role = 'CUSTOMER' AND clinic_id IS NULL)
            OR (role = 'STAFF' AND clinic_id IS NOT NULL)
        )
);

-- 3. Pets owned by customers
CREATE TABLE public.pets (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id   BIGINT NOT NULL,
    name            VARCHAR(100) NOT NULL,
    species         VARCHAR(50) NOT NULL,
    CONSTRAINT fk_pets_owner
        FOREIGN KEY (owner_user_id) REFERENCES public.users(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    -- Required so appointments can enforce pet-owner consistency.
    CONSTRAINT uq_pets_id_owner UNIQUE (id, owner_user_id)
);

-- 4. Services provided by clinics
CREATE TABLE public.services (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_id           BIGINT NOT NULL,
    name                VARCHAR(150) NOT NULL,
    duration_minutes    INTEGER NOT NULL,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_services_clinic
        FOREIGN KEY (clinic_id) REFERENCES public.clinics(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT chk_services_duration CHECK (duration_minutes > 0),
    -- Required so appointments can enforce service-clinic consistency.
    CONSTRAINT uq_services_id_clinic UNIQUE (id, clinic_id)
);

-- 5. Appointment slots created manually by clinic staff
CREATE TABLE public.clinic_slots (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_id   BIGINT NOT NULL,
    slot_date   DATE NOT NULL,
    start_time  TIME WITHOUT TIME ZONE NOT NULL,
    end_time    TIME WITHOUT TIME ZONE NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    CONSTRAINT fk_slots_clinic
        FOREIGN KEY (clinic_id) REFERENCES public.clinics(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_slots_clinic_date_start
        UNIQUE (clinic_id, slot_date, start_time),
    CONSTRAINT chk_slots_time CHECK (end_time > start_time),
    CONSTRAINT chk_slots_status
        CHECK (status IN ('AVAILABLE', 'BOOKED', 'CLOSED')),
    -- Required so appointments can enforce slot-clinic consistency.
    CONSTRAINT uq_slots_id_clinic UNIQUE (id, clinic_id)
);

-- 6. Appointments; cancelled/rejected appointments remain as history
CREATE TABLE public.appointments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_user_id    BIGINT NOT NULL,
    pet_id              BIGINT NOT NULL,
    clinic_id           BIGINT NOT NULL,
    service_id          BIGINT NOT NULL,
    slot_id             BIGINT NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_appointments_customer
        FOREIGN KEY (customer_user_id) REFERENCES public.users(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_pet_owner
        FOREIGN KEY (pet_id, customer_user_id)
        REFERENCES public.pets(id, owner_user_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_clinic
        FOREIGN KEY (clinic_id) REFERENCES public.clinics(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_service_clinic
        FOREIGN KEY (service_id, clinic_id)
        REFERENCES public.services(id, clinic_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_slot_clinic
        FOREIGN KEY (slot_id, clinic_id)
        REFERENCES public.clinic_slots(id, clinic_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT chk_appointments_status
        CHECK (status IN (
            'PENDING', 'CONFIRMED', 'REJECTED',
            'CANCELLED', 'COMPLETED', 'NO_SHOW'
        ))
);

-- A slot can be reused after a previous appointment is cancelled/rejected,
-- but only one PENDING/CONFIRMED appointment may occupy it at a time.
CREATE UNIQUE INDEX uq_appointments_one_active_per_slot
    ON public.appointments (slot_id)
    WHERE status IN ('PENDING', 'CONFIRMED');

-- Indexes for common lookups
CREATE INDEX idx_users_clinic_id
    ON public.users (clinic_id);
CREATE INDEX idx_pets_owner_user_id
    ON public.pets (owner_user_id);
CREATE INDEX idx_services_clinic_active
    ON public.services (clinic_id, is_active);
CREATE INDEX idx_slots_clinic_date_status
    ON public.clinic_slots (clinic_id, slot_date, status);
CREATE INDEX idx_appointments_customer_created
    ON public.appointments (customer_user_id, created_at DESC);
CREATE INDEX idx_appointments_clinic_status
    ON public.appointments (clinic_id, status, created_at DESC);

-- Automatically refresh updated_at when an appointment changes
CREATE OR REPLACE FUNCTION public.set_appointment_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_appointments_updated_at
BEFORE UPDATE ON public.appointments
FOR EACH ROW
EXECUTE FUNCTION public.set_appointment_updated_at();

COMMIT;

-- IMPLEMENTATION NOTES:
-- 1. Use a single @Transactional service method to create appointments.
-- 2. Check the logged-in user's role and active status in Spring Boot.
-- 3. Check the pet belongs to the current customer; the composite FK also helps.
-- 4. Check clinic/service are active and the slot is AVAILABLE.
-- 5. Check the service duration fits the selected slot.
-- 6. Set slot status to BOOKED and insert the PENDING appointment in one transaction.
-- 7. When a cancellation/rejection is valid, update the appointment and reopen the
--    slot in the same transaction. Handle unique-index conflicts as HTTP 409.
-- 8. Staff may only process appointments belonging to their own clinic.
-- 9. Prevent overlapping slot ranges in the slot-creation service. This simplified
--    schema blocks duplicate start times, but not every possible overlapping range.
